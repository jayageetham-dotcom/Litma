// After `next build` (website only): writes apps/web/out/sw.js, the service worker that lets
// https://getlitma.in open and keep working offline (components/ServiceWorker.tsx registers it).
//
//  - Every page, its RSC payload and the build's JS/CSS are precached, so the whole app opens
//    offline after one visit. The list is per build, so a new deploy installs a fresh copy.
//  - Pages: network first (the newest build when online), the cached copy when offline.
//  - /_next/static (content-hashed): cache first.
//  - Dictionary shards, pictures, fonts (also Google Fonts): kept when first used.
//  - The writer's data never passes through here: Supabase is cross-origin and left alone;
//    lib/offline.ts keeps works on the device and syncs them.
// The desktop app doesn't use it (it serves its bundled copy from app://litma/).
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "apps/web/out");
const BASE = process.env.NEXT_PUBLIC_BASE_PATH ?? "";
const { build } = JSON.parse(readFileSync(join(out, "version.json"), "utf8"));

/** never precached: large or server-side files, and files that must always come fresh */
const SKIP = /^(dict|downloads)\/|^(sw\.js|version\.json|mcp\.php|og-image\.jpg|\.htaccess|robots\.txt|sitemap\.xml)$|\.(map|php)$|(^|\/)\.[^/]+$/;
const MAX = 1.5 * 1024 * 1024;

const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    const st = statSync(full);
    if (st.isDirectory()) walk(full);
    else {
      const rel = relative(out, full).split(sep).join("/");
      if (!SKIP.test(rel) && st.size <= MAX) files.push(rel);
    }
  }
})(out);

const urls = files
  .map((rel) => (rel === "index.html" ? "/" : rel.endsWith("/index.html") ? `/${rel.slice(0, -"index.html".length)}` : `/${rel}`))
  .map((u) => BASE + u)
  .sort();

const sw = `// Litma service worker, generated by scripts/write-sw.mjs for build ${build}. Don't edit.
const BUILD = ${JSON.stringify(build)};
const BASE = ${JSON.stringify(BASE)};
const PRECACHE = ${JSON.stringify(urls)};
const SHELL = "litma-shell-" + BUILD;
const RUNTIME = "litma-runtime";
const ALWAYS_NETWORK = /^\\/(version\\.json|sw\\.js|mcp|mcp\\.php|downloads\\/)/;

self.addEventListener("install", (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(SHELL);
      const queue = PRECACHE.slice();
      const worker = async () => {
        for (let url; (url = queue.shift()); ) {
          try {
            // content-hashed files never change: reuse the copy an earlier build kept
            const old = url.includes("/_next/static/") ? await caches.match(url) : undefined;
            if (old) await cache.put(url, old);
            else {
              const res = await fetch(url, { cache: "no-cache" });
              if (res.ok) await cache.put(url, res);
            }
          } catch (e) {
            /* offline during install: the next visit finishes it */
          }
        }
      };
      await Promise.all(Array.from({ length: 6 }, worker));
      await self.skipWaiting();
    })()
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      for (const key of await caches.keys()) if (key.startsWith("litma-shell-") && key !== SHELL) await caches.delete(key);
      await self.clients.claim();
    })()
  );
});

/** the cache key of a page or its RSC payload: no query string (/write/?id=… is /write/) */
const pageKey = (url) => {
  let p = url.pathname;
  if (!p.endsWith("/") && !/\\.[a-z0-9]+$/i.test(p)) p += "/";
  return url.origin + p;
};

async function fromCache(key) {
  return (await caches.match(key, { ignoreSearch: true })) || undefined;
}

/** network first with a time limit; the cached copy when offline or slow */
async function page(request, url) {
  const key = pageKey(url);
  const network = fetch(request).then(async (res) => {
    if (res.ok && res.type === "basic" && !res.redirected) {
      const cache = await caches.open(SHELL);
      await cache.put(key, res.clone());
    }
    return res;
  });
  network.catch(() => {}); // answered from the cache: a late failure isn't an error
  const cached = await fromCache(key);
  if (!cached) {
    try {
      return await network;
    } catch (e) {
      const notFound = await fromCache(url.origin + BASE + "/404.html");
      return notFound || Response.error();
    }
  }
  const slow = new Promise((resolve) => setTimeout(() => resolve(cached), 4000));
  try {
    const res = await Promise.race([network, slow]);
    return res.ok || res === cached ? res : cached;
  } catch (e) {
    return cached;
  }
}

async function cacheFirst(request, store) {
  const hit = await caches.match(request);
  if (hit) return hit;
  const res = await fetch(request);
  if (res.ok || res.type === "opaque") (await caches.open(store)).put(request, res.clone());
  return res;
}

async function staleWhileRevalidate(request, store) {
  const hit = await caches.match(request);
  const fresh = fetch(request)
    .then(async (res) => {
      if (res.ok || res.type === "opaque") await (await caches.open(store)).put(request, res.clone());
      return res;
    })
    .catch(() => hit || Response.error());
  return hit || fresh;
}

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") return;
  const url = new URL(request.url);

  if (url.origin === self.location.origin) {
    if (BASE && !url.pathname.startsWith(BASE)) return;
    const path = url.pathname.slice(BASE.length) || "/";
    if (ALWAYS_NETWORK.test(path)) return;
    if (request.mode === "navigate" || path.endsWith("/") || path.endsWith(".html") || path.endsWith("/index.txt")) return event.respondWith(page(request, url));
    if (path.startsWith("/_next/static/")) return event.respondWith(cacheFirst(request, SHELL));
    return event.respondWith(staleWhileRevalidate(request, RUNTIME));
  }
  if (url.hostname === "fonts.gstatic.com") return event.respondWith(cacheFirst(request, RUNTIME));
  if (url.hostname === "fonts.googleapis.com") return event.respondWith(staleWhileRevalidate(request, RUNTIME));
  // everything else (Supabase, Edge Functions, analytics) goes straight to the network
});
`;

writeFileSync(join(out, "sw.js"), sw);
const kb = Math.round(files.reduce((n, rel) => n + statSync(join(out, rel)).size, 0) / 1024);
console.log(`sw.js → ${urls.length} files precached (${kb} KB)`);
